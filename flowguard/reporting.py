    def generate(self, output_path: str | Path | None = None) -> bytes:
        """Assemble all sections and render the PDF into a binary buffer or file."""
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            leftMargin=40,
            rightMargin=40,
            topMargin=55,
            bottomMargin=55,
        )

        story: list[Any] = []
        story.extend(self.build_cover_page())
        story.extend(self.build_executive_summary())
        story.extend(self.build_metadata_and_scoring_section())
        story.extend(self.build_scenario_results_section())
        story.extend(self.build_findings_section())
        story.extend(self.build_limitations_and_conclusion())

        doc.build(story, canvasmaker=NumberedCanvas)
        pdf_bytes = buffer.getvalue()

        if output_path is not None:
            path = Path(output_path)
            path.parent.mkdir(parents=True, exist_ok=True)
            with open(path, "wb") as f:
                f.write(pdf_bytes)

        return pdf_bytes


