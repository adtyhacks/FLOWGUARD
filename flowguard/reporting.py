class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas that writes running headers and 'Page X of Y' footers.

    Skips running headers and footers on the cover page (page 1).
    """

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self._saved_page_states: list[dict[str, Any]] = []

    def showPage(self) -> None:
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, total_pages: int) -> None:
        """Render running header and footer on pages 2+."""
        if self._pageNumber > 1:
            self.saveState()

            # Running Header
            self.setFont("Helvetica-Bold", 8)
            self.setFillColor(COLOR_TEXT_MUTED)
            self.drawString(40, 755, "FLOWGUARD™ EXECUTIVE SECURITY REPORT")
            self.drawRightString(612 - 40, 755, "CONFIDENTIAL & SANITIZED")
            self.setStrokeColor(COLOR_BORDER)
            self.setLineWidth(0.5)
            self.line(40, 747, 612 - 40, 747)

            # Running Footer
            self.line(40, 42, 612 - 40, 42)
            self.setFont("Helvetica", 8)
            self.drawString(40, 30, "Generated by FLOWGUARD Assessment Engine • E-Commerce Security Verification")
            self.drawRightString(612 - 40, 30, f"Page {self._pageNumber} of {total_pages}")

            self.restoreState()


