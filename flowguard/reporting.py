def escape_for_paragraph(text: Any) -> str:
    """Sanitize secrets and XML-escape text for safe ReportLab Paragraph flowables."""
    if text is None:
        return ""
    # Run through FLOWGUARD recursive sanitization first
    sanitized = str(sanitize_value(text))
    # Escape XML entities
    escaped = (
        sanitized.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
        .replace("'", "&apos;")
    )
    return escaped.replace("\n", "<br/>")


def _normalize_summary(summary: Any) -> dict[str, Any]:
    """Defensively convert an AssessmentSummary or dict into a sanitized dict."""
    if hasattr(summary, "to_dict"):
        data = summary.to_dict()
    elif isinstance(summary, dict):
        data = sanitize_value(dict(summary))
    else:
        data = {}

    data["assessment_id"] = str(data.get("assessment_id") or "UNKNOWN-ID")
    data["target"] = str(data.get("target") or "http://127.0.0.1:5000")
    data["mode"] = str(data.get("mode") or "unknown").lower()
    data["start_time"] = str(data.get("start_time") or datetime.now(timezone.utc).isoformat())
    data["end_time"] = str(data.get("end_time") or data["start_time"])

    # Score handling
    try:
        data["raw_risk_score"] = int(data.get("raw_risk_score") or 0)
    except (TypeError, ValueError):
        data["raw_risk_score"] = 0

    try:
        data["pnri_score"] = float(data.get("pnri_score") or 0.0)
    except (TypeError, ValueError):
        data["pnri_score"] = 0.0

    # Risk band fallback
    if not data.get("risk_band") or data.get("risk_band") == "N/A":
        data["risk_band"] = get_risk_band(data["pnri_score"])

    # Normalize scenario results
    raw_scenarios = data.get("scenario_results") or []
    norm_scenarios = []
    for s in raw_scenarios:
        if hasattr(s, "to_dict"):
            norm_scenarios.append(s.to_dict())
        elif isinstance(s, dict):
            norm_scenarios.append(sanitize_value(dict(s)))
    data["scenario_results"] = norm_scenarios

    # Normalize findings
    raw_findings = data.get("findings") or []
    norm_findings = []
    for f in raw_findings:
        if hasattr(f, "to_dict"):
            norm_findings.append(f.to_dict())
        elif isinstance(f, dict):
            norm_findings.append(sanitize_value(dict(f)))
    data["findings"] = norm_findings

    # Completeness calculation
    if "completeness_pct" not in data or data["completeness_pct"] is None:
        total = len(norm_scenarios)
        if total > 0:
            conclusive = sum(1 for s in norm_scenarios if s.get("status") in ("PASS", "FAIL"))
            data["completeness_pct"] = round((conclusive / total) * 100.0, 1)
            data["is_complete"] = (conclusive == total)
        else:
            data["completeness_pct"] = 100.0
            data["is_complete"] = True
    else:
        try:
            data["completeness_pct"] = float(data["completeness_pct"])
        except (TypeError, ValueError):
            data["completeness_pct"] = 100.0
        data["is_complete"] = bool(data.get("is_complete", data["completeness_pct"] >= 100.0))

    return data


