def create_risk_meter_drawing(pnri_score: float, width: float = 520, height: float = 46) -> Drawing:
    """Generate a clean vector graphic depicting the PNRI score across risk bands."""
    d = Drawing(width, height)
    bar_y = 14
    bar_height = 14

    # 4 risk band segments
    segments = [
        (0.00, 0.20, colors.HexColor("#16A34A"), "Low (0-19.9)"),
        (0.20, 0.50, colors.HexColor("#EAB308"), "Moderate (20-49.9)"),
        (0.50, 0.75, colors.HexColor("#F97316"), "High (50-74.9)"),
        (0.75, 1.00, colors.HexColor("#DC2626"), "Critical (75-100)"),
    ]

    for start_frac, end_frac, col, label in segments:
        seg_x = start_frac * width
        seg_w = (end_frac - start_frac) * width
        d.add(Rect(seg_x, bar_y, seg_w, bar_height, fillColor=col, strokeColor=colors.HexColor("#CBD5E1"), strokeWidth=0.5))
        d.add(String(seg_x + seg_w / 2.0, bar_y - 10, label, fontName="Helvetica", fontSize=7, textAnchor="middle", fillColor=colors.HexColor("#475569")))

    # Indicator pin for current score
    clamped_score = max(0.0, min(100.0, float(pnri_score)))
    indicator_x = (clamped_score / 100.0) * width
    indicator_x = max(25, min(width - 25, indicator_x))

    # Downward pointer triangle
    d.add(Polygon(
        [indicator_x - 5, bar_y + bar_height + 7, indicator_x + 5, bar_y + bar_height + 7, indicator_x, bar_y + bar_height],
        fillColor=colors.HexColor("#0F172A"),
        strokeColor=None,
    ))
    score_label = f"PNRI: {clamped_score:.1f}%"
    d.add(String(indicator_x, bar_y + bar_height + 10, score_label, fontName="Helvetica-Bold", fontSize=8, textAnchor="middle", fillColor=colors.HexColor("#0F172A")))

    return d


